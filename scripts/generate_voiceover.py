"""
Generate the Script 02 voiceover with Kokoro-82M (open-weight, Apache-2.0) via kokoro-onnx,
then place every line on the video timeline so it lands with its scene.

Setup (once, in any virtualenv):
    pip install kokoro-onnx soundfile
    # model + voices from https://huggingface.co/onnx-community/Kokoro-82M-v1.0-ONNX
    #   onnx/model.onnx  and  voices/<voice>.bin   -> put them in MODEL_DIR (model.onnx, voices/*.bin)

Run:
    python scripts/generate_voiceover.py MODEL_DIR [--voice af_heart] [--measure]
    -> public/audio/sancho-chasing-vo.wav (24 s, aligned to the 720-frame composition)
"""
import argparse
import os

import numpy as np
import soundfile as sf
from kokoro_onnx import Kokoro

SR = 24000
DUR = 24.0

# (start second, text, speed). Starts follow the scene beats in src/chasing/timeline.ts.
# Narration from Script 02, lightly tightened so every line fits its scene at a natural pace
# (the verbatim script reads ~26 s of speech for a 24 s video). Key phrases are kept.
LINES = [
    (0.25, "When your parents live back home, finding out what the doctor said shouldn't feel like detective work.", 1.05),
    (5.6, "Meet Sancho.", 0.95),  # lands with the logo (frame 180)
    (6.95, "Stay informed through a professional care process, without chasing your parents for answers.", 1.05),
    (12.65, "Behind every update, Sancho's system stays on top of ongoing care, so nothing important slips.", 1.05),
    (18.75, "Stay informed with calm confidence, from anywhere.", 1.0),
    (21.75, "Download Sancho now.", 0.95),  # with the logo + Download Now button
]


def load(model_dir):
    voices = {}
    for f in os.listdir(os.path.join(model_dir, 'voices')):
        if f.endswith('.bin'):
            voices[f[:-4]] = np.fromfile(os.path.join(model_dir, 'voices', f), dtype=np.float32).reshape(-1, 1, 256)
    npz = os.path.join(model_dir, 'voices.npz')
    np.savez(npz, **voices)
    return Kokoro(os.path.join(model_dir, 'model.onnx'), npz)


def trim(x, thresh=0.01):
    idx = np.nonzero(np.abs(x) > thresh)[0]
    return x if len(idx) == 0 else x[max(0, idx[0] - 240) : idx[-1] + 1200]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('model_dir')
    ap.add_argument('--voice', default='af_heart')
    ap.add_argument('--measure', action='store_true', help='print natural line durations and exit')
    ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'public', 'audio', 'sancho-chasing-vo.wav'))
    ap.add_argument('--timing', default=None, help='write speech spans to this .ts file')
    a = ap.parse_args()
    k = load(a.model_dir)

    track = np.zeros(int(DUR * SR), dtype=np.float32)
    prev_end = 0.0
    spans = []
    for start, text, speed in LINES:
        audio, sr = k.create(text, voice=a.voice, speed=speed, lang='en-us')
        assert sr == SR
        audio = trim(np.asarray(audio, dtype=np.float32))
        length = len(audio) / SR
        flag = '  <-- overlaps previous line' if start < prev_end - 0.05 else ''
        print(f'{start:6.2f}s  {length:5.2f}s  ends {start + length:6.2f}s  x{speed}  {text[:60]}{flag}')
        prev_end = start + length
        spans.append((round(start, 3), round(start + length, 3)))
        if a.measure:
            continue
        i0 = int(start * SR)
        seg = audio[: len(track) - i0]
        track[i0 : i0 + len(seg)] += seg
    if a.measure:
        return
    track *= 10 ** (-3 / 20) / max(1e-6, np.abs(track).max())  # -3 dBFS peak
    sf.write(a.out, track, SR, subtype='PCM_16')
    print('wrote', os.path.abspath(a.out))
    if a.timing:
        with open(a.timing, 'w') as f:
            f.write('// Generated by scripts/generate_voiceover.py — speech spans in seconds, used to duck the music.\n')
            f.write('export const VO_SPANS: [number, number][] = [\n')
            for st, en in spans:
                f.write(f'  [{st}, {en}],\n')
            f.write('];\n')
        print('wrote', os.path.abspath(a.timing))


if __name__ == '__main__':
    main()
