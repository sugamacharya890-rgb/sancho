"""
Nepali voiceover for SanchoChasingVideo (Script 02), synthesized offline with Piper.

Voices (https://huggingface.co/rhasspy/piper-voices, ne/ne_NP):
  chitwan/medium  — 1 speaker, dataset CC0
  google/medium   — 18 speakers, dataset OpenSLR 43, CC-BY-SA-4.0

Setup:  pip install "piper-tts>=1.5" soundfile numpy
Run:    python scripts/generate_voiceover_ne.py VOICE_DIR [--voice chitwan|google] [--speaker N] [--measure]
        -> public/audio/sancho-chasing-vo-ne.wav  (+ optional --timing src/chasing/voiceoverTimingNe.ts)
"""
import argparse
import os

import numpy as np
import soundfile as sf
from piper import PiperVoice, SynthesisConfig

DUR = 24.0

# (start second, Nepali line, length_scale) — same scene anchors as the English VO.
# English source (Script 02, tightened):
#  1 When your parents live back home, finding out what the doctor said shouldn't feel like detective work.
#  2 Meet Sancho.
#  3 Stay informed through a professional care process, without chasing your parents for answers.
#  4 Behind every update, Sancho's system stays on top of ongoing care, so nothing important slips.
#  5 Stay informed with calm confidence, from anywhere.
#  6 Download Sancho now.
# Loanwords use a halant (अप्डेट, डाउन्लोड) so espeak doesn't insert an extra vowel.
LINES = [
    (0.25, "आमाबुबा नेपालमा हुनुहुन्छ भने, डाक्टरले के भन्नुभयो भनेर थाहा पाउन जासुसी गरेझैं गर्नु नपरोस्।", 1.0),
    (5.6, "प्रस्तुत छ, सन्चो।", 1.0),
    (6.95, "आमाबुबालाई बारम्बार सोधिरहनु नपरी, व्यावसायिक हेरचाह प्रक्रियामार्फत सधैं जानकारीमा रहनुहोस्।", 1.0),
    (12.65, "हरेक अप्डेटको पछाडि, सन्चोको प्रणालीले निरन्तर हेरचाहको पूरा ख्याल राख्छ, ताकि कुनै पनि महत्त्वपूर्ण कुरा नछुटोस्।", 1.0),
    (18.75, "जहाँबाट पनि, ढुक्क भएर जानकारीमा रहनुहोस्।", 1.0),
    (21.75, "आजै सन्चो डाउन्लोड गर्नुहोस्।", 1.0),
]

FILES = {'chitwan': 'ne_NP-chitwan-medium.onnx', 'google': 'ne_NP-google-medium.onnx'}


def synth(voice, text, speaker, length_scale):
    cfg = SynthesisConfig(speaker_id=speaker, length_scale=length_scale, noise_scale=0.5, noise_w_scale=0.333)
    return np.concatenate([c.audio_float_array for c in voice.synthesize(text, syn_config=cfg)]).astype(np.float32)


def trim(x, sr, thresh=0.01):
    idx = np.nonzero(np.abs(x) > thresh)[0]
    return x if len(idx) == 0 else x[max(0, idx[0] - int(0.01 * sr)) : idx[-1] + int(0.05 * sr)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('voice_dir')
    ap.add_argument('--voice', default='chitwan', choices=FILES)
    ap.add_argument('--speaker', type=int, default=None)
    ap.add_argument('--scale', type=float, default=1.0, help='global length_scale multiplier (<1 = faster)')
    ap.add_argument('--measure', action='store_true')
    ap.add_argument('--timing', default=None)
    ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'public', 'audio', 'sancho-chasing-vo-ne.wav'))
    a = ap.parse_args()

    voice = PiperVoice.load(os.path.join(a.voice_dir, FILES[a.voice]))
    sr = voice.config.sample_rate
    track = np.zeros(int(DUR * sr), dtype=np.float32)
    spans, prev_end = [], 0.0
    for start, text, ls in LINES:
        audio = trim(synth(voice, text, a.speaker, ls * a.scale), sr)
        length = len(audio) / sr
        flag = '  <-- overlaps' if start < prev_end - 0.05 else ''
        print(f'{start:6.2f}s  {length:5.2f}s  ends {start + length:6.2f}s{flag}')
        prev_end = start + length
        spans.append((round(start, 3), round(start + length, 3)))
        if not a.measure:
            i0 = int(start * sr)
            seg = audio[: len(track) - i0]
            track[i0 : i0 + len(seg)] += seg
    if a.measure:
        return
    track *= 10 ** (-3 / 20) / max(1e-6, np.abs(track).max())
    sf.write(a.out, track, sr, subtype='PCM_16')
    print('wrote', os.path.abspath(a.out))
    if a.timing:
        with open(a.timing, 'w') as f:
            f.write('// Generated by scripts/generate_voiceover_ne.py — Nepali speech spans in seconds, used to duck the music.\n')
            f.write('export const VO_SPANS_NE: [number, number][] = [\n')
            for st, en in spans:
                f.write(f'  [{st}, {en}],\n')
            f.write('];\n')
        print('wrote', os.path.abspath(a.timing))


if __name__ == '__main__':
    main()
